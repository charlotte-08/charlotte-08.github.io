const art = document.querySelector("#ascii-art");
const title = document.querySelector("#scene-title");
const description = document.querySelector("#scene-description");
const count = document.querySelector("#scene-count");
const controls = [...document.querySelectorAll("[data-scene]")];
const reduceMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;

let sceneIndex = 0;
let frameIndex = 0;
let frameTimer;
let sceneTimer;

function render() {
  const scene = scenes[sceneIndex];
  art.textContent = scene.frames[frameIndex];
  title.textContent = scene.title;
  description.textContent = scene.description;
  count.textContent = `${String(sceneIndex + 1).padStart(2, "0")} / ${String(scenes.length).padStart(2, "0")}`;
  controls.forEach((control, index) => control.classList.toggle("is-active", index === sceneIndex));
}

function startAnimation() {
  clearInterval(frameTimer);
  clearInterval(sceneTimer);
  frameIndex = 0;
  render();

  if (reduceMotion) return;

  frameTimer = setInterval(() => {
    frameIndex = (frameIndex + 1) % scenes[sceneIndex].frames.length;
    render();
  }, 420);

  sceneTimer = setInterval(() => {
    sceneIndex = (sceneIndex + 1) % scenes.length;
    frameIndex = 0;
    render();
  }, 3600);
}

controls.forEach(control => {
  control.addEventListener("click", () => {
    sceneIndex = Number(control.dataset.scene);
    startAnimation();
  });
});

startAnimation();
